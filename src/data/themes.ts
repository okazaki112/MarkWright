export interface ThemeFonts {
  /** UI 文字（按钮/标签/状态栏）*/
  sans: string
  /** 正文（预览/段落）*/
  serif: string
  /** 标题/品牌 */
  display: string
  /** 代码 */
  mono: string
}

export interface ThemeMeta {
  id: string
  name: string
  author: string
  description: string
  isDark: boolean
  /** 预览用色板（4 色） */
  swatch: { name: string; color: string }[]
  /** CSS 变量集（颜色 + 装饰 + 纹理） */
  vars: Record<string, string>
  /** 字体族 */
  fonts: ThemeFonts
  /** 装饰模式 */
  decoration: DecorationMode
  /** 背景纹理 */
  surface: SurfacePattern
  /** 动效 */
  motion: MotionMode
  /** 密度 */
  density: DensityMode
}

