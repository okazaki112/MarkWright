/**
 * 主题市场 · 纯数据层（从 theme store 拆出，v0.4.8）
 *
 * 6 个渲染维度：
 *  1. Palette        - 颜色（CSS 变量）
 *  2. Typography    - 字体族 / 行高 / 字号
 *  3. Surface       - 背景纹理（纯色/网格/纸张/星点/极光）
 *  4. Decoration    - 装饰元素（标题色条/卡片阴影/圆角/纸张边距）
 *  5. Motion        - 微动效（sharp/smooth/glow）
 *  6. Density       - 信息密度（compact/standard/loose）
 *
 * 字体策略：本地系统字体优先，不下载外部字体
 */

export type DecorationMode = 'flat' | 'paper' | 'bar' | 'card'
export type SurfacePattern = 'none' | 'grid' | 'paper' | 'stars' | 'aurora' | 'lines'
export type MotionMode = 'sharp' | 'smooth' | 'glow' | 'float'
export type DensityMode = 'compact' | 'standard' | 'loose'

/**
 * 正文渲染风格家族（应用到 <html data-content>）。
 * 决定标题 / 行内元素 / 代码块 / 引用 / 列表 / 表格 / 分割线等元素的渲染设计，
 * 详见 styles/content-themes.css
 */
export type ContentStyle = 'modern' | 'github' | 'book' | 'obsidian' | 'nord' | 'neon'

